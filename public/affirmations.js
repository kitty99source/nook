export function pickAffirmation(previous) {
  const list = AFFIRMATIONS;
  if (!list.length) return '';
  let index = Math.floor(Math.random() * list.length);
  if (list.length > 1 && list[index] === previous) index = (index + 1) % list.length;
  return list[index];
}
